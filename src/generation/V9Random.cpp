constexpr double NORMAL_RADIUS = 3.6'541'528'853'610'087'963'519'472'518;
constexpr double INVERSE_NORMAL_RADIUS = 0.27'366'123'732'975'827'203'338'247'596;

// NumPy's random_standard_normal transform consumes full 64-bit PCG draws.
double normalSample(NumpyRandom& random)
{
    for (;;)
    {
        uint64_t bits = random.randomRaw();
        uint64_t const index = static_cast<uint64_t>(bits & 0xffU);
        bits >>= 8U;
        bool const negative = (bits & 1U) != 0U;
        uint64_t const magnitude = (bits >> 1U) & 0x000f'ffff'ffff'ffffULL;
        double value = static_cast<double>(magnitude) * NORMAL_WIDTHS[index];
        if (negative)
        {
            value = -value;
        }
        if (magnitude < NORMAL_THRESHOLDS[index])
        {
            return value;
        }
        if (index == 0U)
        {
            for (;;)
            {
                double const x = -INVERSE_NORMAL_RADIUS * std::log1p(-random.random());
                double const y = -std::log1p(-random.random());
                if (y + y > x * x)
                {
                    return ((magnitude >> 8U) & 1U) != 0U ? -(NORMAL_RADIUS + x)
                            : NORMAL_RADIUS + x;
                }
            }
        }
        else if (std::fma(NORMAL_HEIGHTS[index - 1U] - NORMAL_HEIGHTS[index], random.random(),
                          NORMAL_HEIGHTS[index]) < std::exp(-0.5 * value * value))
        {
            return value;
        }
    }
}

