std::vector<double> v9NormalSamples(uint64_t seed, uint64_t count)
{
    NumpyRandom random(seed);
    std::vector<double> samples(count);
    for (double& sample : samples)
    {
        sample = normalSample(random);
    }
    return samples;
}

